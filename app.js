/* ==================== الإحصائيات ==================== */

function updateStats() {
    document.getElementById('statBuses').innerText = buses.length;
    document.getElementById('statSupervisors').innerText = supervisors.length;
    document.getElementById('statStudents').innerText = students.length;

    let totalSalaries = 0, totalAdvances = 0, totalAbsenceDeductions = 0;
    buses.forEach(b => {
        totalSalaries += Number(b.salary || 0);
        if (b.advances) b.advances.forEach(adv => totalAdvances += Number(adv.amount || 0));
    });
    absences.forEach(ab => {
        if (ab.hasSubstitute === 'no') totalAbsenceDeductions += Number(ab.amount || 0);
    });

    document.getElementById('statTotalAdvances').innerText = (totalAdvances + totalAbsenceDeductions).toLocaleString() + ' ر.ي';
    document.getElementById('statNetSalaries').innerText = (totalSalaries - totalAdvances - totalAbsenceDeductions).toLocaleString() + ' ر.ي';
}

