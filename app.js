function saveBus(e) {
    e.preventDefault();
    const id = document.getElementById('busId').value;
    const existing = buses.find(b => b.id === id);
    const busData = {
        id: id || 'b_' + Date.now(),
        name: document.getElementById('busName').value,
        plate: document.getElementById('busPlate').value,
        driver: document.getElementById('busDriver').value,
        driverPhone: document.getElementById('busDriverPhone').value,
        route: document.getElementById('busRoute').value,
        salary: Number(document.getElementById('busSalary').value || 0),
        advances: existing ? existing.advances : []
    };
    if (id) {
        buses = buses.map(b => b.id === id ? busData : b);
        showNotification('تم التحديث', 'تم تعديل بيانات الباص');
    } else {
        buses.push(busData);
        showNotification('تم الإضافة', 'تمت إضافة الباص');
    }
    saveData(); closeBusModal(); renderBuses();
}

