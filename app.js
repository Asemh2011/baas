function renderReports() {
    const container = document.getElementById('reportsContainer');
    container.innerHTML = '';
    if (buses.length === 0) {
        container.innerHTML = '<p class="text-center text-slate-400 py-10">لا توجد بيانات باصات لعمل التقارير.</p>';
        return;
    }
    buses.forEach(b => {
        const sup = supervisors.find(s => s.busId === b.id);
        const busStudents = students.filter(st => st.busId === b.id);
        const busComplaints = complaints.filter(c => c.busId === b.id);
        let busAdvances = 0;
        if (b.advances) b.advances.forEach(a => busAdvances += Number(a.amount));
        let busAbsenceDeduction = 0;
        absences.forEach(ab => {
            if (ab.busId === b.id && ab.hasSubstitute === 'no') busAbsenceDeduction += Number(ab.amount);
        });
        const busNet = Number(b.salary || 0) - busAdvances - busAbsenceDeduction;

        let studentsListHtml = '';
        if (busStudents.length === 0) {
            studentsListHtml = '<p class="text-xs text-slate-400 italic">لا يوجد طلاب مسجلين على هذا الباص.</p>';
        } else {
            studentsListHtml = '<ul class="space-y-1 text-xs text-slate-600 max-h-40 overflow-y-auto">';
            busStudents.slice(0, 20).forEach((st, idx) => {
                studentsListHtml += `<li class="bg-slate-50 p-2 rounded-lg flex justify-between items-center"><span><strong>${idx + 1}. ${st.name}</strong> (${st.grade})</span><span class="text-slate-500">${st.section || ''}</span></li>`;
            });
            if (busStudents.length > 20) {
                studentsListHtml += `<li class="text-center text-xs text-indigo-600 font-bold py-2">... و ${busStudents.length - 20} طالب آخر</li>`;
            }
            studentsListHtml += '</ul>';
        }

        let complaintsListHtml = '';
        if (busComplaints.length > 0) {
            complaintsListHtml = '<div class="mt-4 pt-3 border-t border-slate-200"><h5 class="font-bold text-xs text-rose-700 mb-2">شكاوى الباص:</h5><ul class="space-y-1 text-xs">';
            busComplaints.forEach(cp => {
                complaintsListHtml += `<li class="bg-rose-50/50 p-2 rounded text-slate-700"><strong>${cp.title}:</strong> ${cp.details}</li>`;
            });
            complaintsListHtml += '</ul></div>';
        }

        container.innerHTML += `
            <div class="bg-white rounded-2xl p-6 shadow-sm border border-slate-100">
                <div class="flex flex-wrap justify-between items-center border-b border-slate-100 pb-4 mb-4 gap-2">
                    <div>
                        <span class="bg-indigo-900 text-white text-xs font-bold px-3 py-1 rounded-lg">${b.driver}</span>
                        <h3 class="text-xl font-bold text-slate-800 mt-1">${b.name} - الوجهة: <span class="text-indigo-600">${b.route}</span></h3>
                    </div>
                    <div class="text-left">
                        <p class="text-xs text-slate-500 font-semibold">إجمالي الطلاب: <span class="text-amber-600 font-bold">${busStudents.length} طالب</span></p>
                    </div>
                </div>
                <div class="grid grid-cols-1 md:grid-cols-2 gap-6 mb-2">
                    <div class="bg-slate-50 p-4 rounded-xl border border-slate-100">
                        <h4 class="font-bold text-slate-800 text-sm mb-2 flex items-center gap-2"><i class="fa-solid fa-wallet text-indigo-700"></i> الاستحقاق والرواتب</h4>
                        <p class="text-xs text-slate-600 mb-1"><strong>السائق:</strong> ${b.driver} (${b.driverPhone})</p>
                        <p class="text-xs text-slate-600 mb-1"><strong>المشرف/ة:</strong> ${sup ? sup.name + ' (' + sup.phone + ')' : '<span class="text-rose-500">غير معين</span>'}</p>
                        <div class="mt-3 pt-3 border-t border-slate-200 text-xs space-y-1">
                            <p>الراتب الأساسي: <strong>${Number(b.salary || 0).toLocaleString()} ر.ي</strong></p>
                            <p>السحبيات: <strong class="text-rose-600">${busAdvances.toLocaleString()} ر.ي</strong></p>
                            <p>خصومات الغياب: <strong class="text-amber-600">${busAbsenceDeduction.toLocaleString()} ر.ي</strong></p>
                            <p>الصافي المستحق: <strong class="text-emerald-600 font-black text-sm">${busNet.toLocaleString()} ر.ي</strong></p>
                        </div>
                    </div>
                    <div>
                        <h4 class="font-bold text-slate-800 text-sm mb-2 flex items-center gap-2"><i class="fa-solid fa-users text-amber-600"></i> قائمة الطلاب (${busStudents.length})</h4>
                        ${studentsListHtml}
                    </div>
                </div>
                ${complaintsListHtml}
            </div>`;
    });
}

