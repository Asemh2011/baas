function exportCurrentTab() {
    let exportDataObj = {};
    let fileName = 'export_' + activeTabName + '_' + new Date().toISOString().split('T')[0] + '.json';

    if (activeTabName === 'buses') exportDataObj = { type: 'buses', data: buses };
    else if (activeTabName === 'supervisors') exportDataObj = { type: 'supervisors', data: supervisors };
    else if (activeTabName === 'students') exportDataObj = { type: 'students', data: students };
    else if (activeTabName === 'absence') exportDataObj = { type: 'absences', data: absences };
    else if (activeTabName === 'complaints') exportDataObj = { type: 'complaints', data: complaints };
    else if (activeTabName === 'reports') exportDataObj = { type: 'reports_summary', buses, supervisors, students, absences, complaints };

    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(exportDataObj, null, 2));
    const a = document.createElement('a');
    a.setAttribute("href", dataStr);
    a.setAttribute("download", fileName);
    document.body.appendChild(a);
    a.click();
    a.remove();
    showNotification('تم التصدير', 'تم التصدير بنجاح');
}

function importCurrentTab() {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = '.json';
    input.onchange = e => {
        const file = e.target.files[0];
        const reader = new FileReader();
        reader.onload = event => {
            try {
                const parsed = JSON.parse(event.target.result);
                if (activeTabName === 'buses' && parsed.type === 'buses' && Array.isArray(parsed.data)) {
                    buses = parsed.data;
                } else if (activeTabName === 'supervisors' && parsed.type === 'supervisors' && Array.isArray(parsed.data)) {
                    supervisors = parsed.data;
                } else if (activeTabName === 'students' && parsed.type === 'students' && Array.isArray(parsed.data)) {
                    students = parsed.data;
                } else if (activeTabName === 'absence' && parsed.type === 'absences' && Array.isArray(parsed.data)) {
                    absences = parsed.data;
                } else if (activeTabName === 'complaints' && parsed.type === 'complaints' && Array.isArray(parsed.data)) {
                    complaints = parsed.data;
                } else if (activeTabName === 'reports' && parsed.buses) {
                    buses = parsed.buses;
                    supervisors = parsed.supervisors || supervisors;
                    students = parsed.students || students;
                    absences = parsed.absences || absences;
                    complaints = parsed.complaints || complaints;
                } else {
                    showNotification('خطأ', 'الملف لا يتطابق', 'error');
                    return;
                }
                saveData(); renderBuses(); renderSupervisors(); renderStudents();
                if (activeTabName === 'absence') renderAbsences();
                if (activeTabName === 'complaints') renderComplaints();
                if (activeTabName === 'reports') renderReports();
                showNotification('نجاح', 'تم الاستيراد بنجاح');
            } catch (err) {
                showNotification('خطأ', 'فشل قراءة الملف', 'error');
            }
        };
        reader.readAsText(file);
    };
    input.click();
}

